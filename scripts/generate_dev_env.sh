#!/usr/bin/env bash
# Create a local .env with random development credentials.
# Does not print secrets. Refuses to overwrite an existing .env.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TARGET="$ROOT/.env"

if [[ -f "$TARGET" ]]; then
  echo "Refusing to overwrite existing .env at $TARGET"
  exit 1
fi

if ! command -v openssl >/dev/null 2>&1; then
  echo "openssl is required to generate a development password."
  exit 1
fi

PASSWORD="$(openssl rand -hex 24)"
USER_NAME="supportflow_dev"
DB_NAME="supportflow"

cat > "$TARGET" <<EOF
# Local development configuration — DO NOT COMMIT
# Generated by scripts/generate_dev_env.sh

APP_ENV=development
APP_NAME=SupportFlow AI

POSTGRES_USER=${USER_NAME}
POSTGRES_PASSWORD=${PASSWORD}
POSTGRES_DB=${DB_NAME}
POSTGRES_HOST=db
POSTGRES_PORT=5432

# Used by containers on the Compose network (host=db).
DATABASE_URL=postgresql+psycopg://${USER_NAME}:${PASSWORD}@db:5432/${DB_NAME}

# Phase 2.1 — Ollama on Mac host (API container uses host.docker.internal)
OLLAMA_BASE_URL=http://host.docker.internal:11434
OLLAMA_MODEL=qwen3:1.7b
OLLAMA_CONNECT_TIMEOUT_SECONDS=5
OLLAMA_INFERENCE_TIMEOUT_SECONDS=60
OLLAMA_NUM_CTX=2048
OLLAMA_NUM_PREDICT=128
OLLAMA_MAX_CONCURRENCY=1
OLLAMA_TEMPERATURE=0
REQUIRE_HUMAN_APPROVAL=true
CLAIM_LIVE_COURIER_TRACKING=false
EOF

chmod 600 "$TARGET"
echo "Wrote $TARGET with generated development credentials (secrets not printed)."
